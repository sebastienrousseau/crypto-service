/** Builds the DORA self-assessment for the current request. */
export function buildDoraSelfAssessment(
  now: Date = new Date(),
): DoraSelfAssessment {
  return {
    standard: "DORA (EU 2022/2554)",
    article: "Article 9 & Article 13",
    status: "Self-assessment (not a compliance verdict)",
    disclaimer: DISCLAIMER,
    quantumResistanceRatio:
      Math.round((POST_QUANTUM_COUNT / ALGORITHM_IDS.size) * 100) / 100,
    activePrimitivesCount: ALGORITHM_IDS.size,
    postQuantumPrimitivesCount: POST_QUANTUM_COUNT,
    algorithmDeprecationSchedule: DEPRECATION_SCHEDULE,
    cryptographicInventory: INVENTORY.map((record) => ({
      ...record,
      version: readPackageVersion(
        record.package.replace("@sebastienrousseau/", ""),
      ),
    })),
    timestamp: now.toISOString(),
  };
}

