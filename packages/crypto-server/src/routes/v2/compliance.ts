/**
 * Directory holding the `@sebastienrousseau/*` package folders: `packages/`
 * in the monorepo, `node_modules/@sebastienrousseau/` when installed. The
 * same relative path works from `src/routes/v2` and `dist/routes/v2`.
 */
const PACKAGES_ROOT = path.resolve(__dirname, "..", "..", "..", "..");

/**
 * Reads the `version` field of a sibling package's package.json.
 *
 * @param dir - Package folder name, e.g. `"crypto-lib"`.
 * @returns The version, or `"unknown"` when the package is not present.
 */
export function readPackageVersion(dir: string): string {
  try {
    const file = path.join(PACKAGES_ROOT, dir, "package.json");
    return (JSON.parse(readFileSync(file, "utf8")) as { version: string })
      .version;
  } catch {
    return "unknown";
  }
}

/** One entry of the self-reported package inventory. */
export interface InventoryRecord {
  readonly package: string;
  readonly version: string;
  readonly status: "implemented" | "partial" | "placeholder";
  /** Factual statement of what the package implements (field name kept for API compatibility). */
  readonly fipsCompliance: string;
}

/** Self-reported cryptographic inventory; not a compliance verdict. */
export interface DoraSelfAssessment {
  readonly standard: "DORA (EU 2022/2554)";
  readonly article: "Article 9 & Article 13";
  readonly status: string;
  readonly disclaimer: string;
  readonly quantumResistanceRatio: number;
  readonly activePrimitivesCount: number;
  readonly postQuantumPrimitivesCount: number;
  readonly algorithmDeprecationSchedule: ReadonlyArray<{
    readonly algorithm: string;
    readonly category: "symmetric" | "asymmetric";
    readonly sunsetDate: string;
    readonly recommendedMigration: string;
  }>;
  readonly cryptographicInventory: ReadonlyArray<InventoryRecord>;
  readonly timestamp: string;
}

