#!/usr/bin/env node
// SPDX-License-Identifier: Apache-2.0 OR MIT
//
// Write the crypto-server OpenAPI 3.1 document to
// openapi/crypto-service.openapi.yaml, the contract SDKs in other
// languages are generated from. It boots the built server
// (packages/crypto-server/dist, so build first) with the docs enabled,
// takes the document @fastify/swagger generates from the route schemas,
// sets info.version to the root package version and writes it with every
// key sorted, so a diff shows only real changes. With --check it writes
// nothing and exits 1 when the committed file differs.

import { createRequire } from "node:module";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { runIfMain } from "./lib/cli.mjs";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
export const SPEC_PATH = "openapi/crypto-service.openapi.yaml";

/** Top-level members in the order the OpenAPI specification lists them. */
const TOP_LEVEL = [
  "openapi",
  "info",
  "jsonSchemaDialect",
  "servers",
  "security",
  "tags",
  "paths",
  "webhooks",
  "components",
  "externalDocs",
];

const isObject = (v) =>
  v !== null && typeof v === "object" && !Array.isArray(v);

/** Top-level keys first in OpenAPI order, then the rest sorted. */
function topLevelOrder(keys) {
  const known = TOP_LEVEL.filter((k) => keys.includes(k));
  return known.concat(keys.filter((k) => !TOP_LEVEL.includes(k)).sort());
}

/**
 * A copy of `value` with every object's keys sorted (the top level in
 * OpenAPI order). Arrays keep their order: in JSON Schema it can matter.
 */
export function canonical(value, top = true) {
  if (Array.isArray(value)) return value.map((v) => canonical(v, false));
  if (!isObject(value)) return value;
  const keys = Object.keys(value);
  const ordered = top ? topLevelOrder(keys) : keys.sort();
  return Object.fromEntries(
    ordered.map((k) => [k, canonical(value[k], false)]),
  );
}

/** A string YAML reads back as the same string without quotes. */
const PLAIN = /^[A-Za-z_][A-Za-z0-9_.-]*$/;
/** Plain words YAML 1.1 or 1.2 would read as booleans or null. */
const RESERVED = /^(?:true|false|null|yes|no|on|off|y|n)$/i;

/** A scalar as YAML: plain when unambiguous, else JSON (double-quoted). */
export function scalar(value) {
  if (typeof value === "string" && PLAIN.test(value) && !RESERVED.test(value)) {
    return value;
  }
  return JSON.stringify(value);
}

/** Whether a value is written as an indented block. */
const isBlock = (v) =>
  (Array.isArray(v) && v.length > 0) ||
  (isObject(v) && Object.keys(v).length > 0);

/** A value that fits on its key's or dash's line. */
function inline(value) {
  if (Array.isArray(value)) return "[]";
  if (isObject(value)) return "{}";
  return scalar(value);
}

/** The lines of a block value, indented by `indent` spaces. */
function block(value, indent) {
  const pad = " ".repeat(indent);
  if (Array.isArray(value)) {
    return value.flatMap((item) => {
      if (!isBlock(item)) return [`${pad}- ${inline(item)}`];
      const [first, ...rest] = block(item, indent + 2);
      return [`${pad}- ${first.slice(indent + 2)}`, ...rest];
    });
  }
  return Object.entries(value).flatMap(([key, v]) =>
    isBlock(v)
      ? [`${pad}${scalar(key)}:`, ...block(v, indent + 2)]
      : [`${pad}${scalar(key)}: ${inline(v)}`],
  );
}

/** A JSON value as a YAML 1.2 document (block style). */
export function toYaml(value) {
  return isBlock(value)
    ? `${block(value, 0).join("\n")}\n`
    : `${inline(value)}\n`;
}

const HEADER =
  "# SPDX-License-Identifier: Apache-2.0 OR MIT\n" +
  "# Generated by scripts/export-openapi.mjs from the crypto-server route\n" +
  "# schemas; do not edit. Regenerate with `pnpm run openapi`.\n";

/** The committed file's text for a generated document. */
export function render(spec, version) {
  const doc = JSON.parse(JSON.stringify(spec));
  doc.info = { ...doc.info, version };
  return HEADER + toYaml(canonical(doc));
}

/**
 * A short account of how `actual` differs from `expected`, line by line:
 * how many lines differ and the first `limit` of them.
 */
export function diffSummary(expected, actual, limit = 10) {
  const want = expected.split("\n");
  const got = actual.split("\n");
  const lines = [];
  for (let i = 0; i < Math.max(want.length, got.length); i++) {
    if (want[i] !== got[i]) lines.push(i + 1);
  }
  const shown = lines
    .slice(0, limit)
    .flatMap((n) => [
      `  line ${n}:`,
      `    - ${want[n - 1] ?? "(none)"}`,
      `    + ${got[n - 1] ?? "(none)"}`,
    ]);
  const more =
    lines.length > limit ? [`  ... and ${lines.length - limit} more`] : [];
  return [`${lines.length} line(s) differ`, ...shown, ...more].join("\n");
}

/**
 * Boot the built server with the docs and the deprecated v1 routes on,
 * whatever the environment says, and return its document.
 */
export async function generate(root = ROOT) {
  process.env["DOCS_ENABLED"] = "1";
  process.env["V1_ENABLED"] = "1";
  const require = createRequire(import.meta.url);
  const { init } = require(`${root}packages/crypto-server/dist/server.js`);
  const app = await init({ logger: false });
  try {
    return app.swagger();
  } finally {
    await app.close();
  }
}

/** Write or (`--check`) verify the document; resolves to the exit code. */
export async function main(
  argv,
  {
    root = ROOT,
    document = generate,
    log = console.log,
    error = console.error,
  } = {},
) {
  const version = JSON.parse(
    readFileSync(`${root}package.json`, "utf8"),
  ).version;
  const next = render(await document(root), version);
  const path = `${root}${SPEC_PATH}`;
  if (!argv.includes("--check")) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, next);
    log(`export-openapi: wrote ${SPEC_PATH}`);
    return 0;
  }
  const current = existsSync(path) ? readFileSync(path, "utf8") : "";
  if (current === next) {
    log(`export-openapi: ok (${SPEC_PATH})`);
    return 0;
  }
  error(
    `export-openapi: ${SPEC_PATH} is out of date; run pnpm run openapi\n` +
      diffSummary(current, next),
  );
  return 1;
}

await runIfMain(import.meta.url, main, { name: "export-openapi" });
